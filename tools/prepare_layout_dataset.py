#!/usr/bin/env python3
"""Convert a document-layout dataset into YOLO training format.

Tested against DocLayNet (the dataset the shipped layout model was trained on,
so the class names line up exactly). The converter reads the per-page JSON
annotations, writes one ``.txt`` label file per image and a ``data.yaml`` that
Ultralytics can train from.

Usage:
    python3 tools/prepare_layout_dataset.py \
        --source /home/ubuntu/datasets/small_dataset \
        --output data/layout_dataset

DocLayNet annotation boxes are ``[x, y, width, height]`` in pixels (not
``x1, y1, x2, y2``), which is a common source of silently wrong labels, so the
conversion is explicit about it.
"""

from __future__ import annotations

import argparse
import json
import shutil
from collections import Counter
from pathlib import Path

#: DocLayNet classes, in the order the shipped model uses.
CLASSES = [
    "Caption",
    "Footnote",
    "Formula",
    "List-item",
    "Page-footer",
    "Page-header",
    "Picture",
    "Section-header",
    "Table",
    "Text",
    "Title",
]
CLASS_INDEX = {name: index for index, name in enumerate(CLASSES)}

SPLITS = ("train", "val", "test")


def convert_split(source: Path, output: Path, split: str) -> Counter:
    """Convert one split; returns the class histogram."""
    image_dir = source / split / "images"
    annotation_dir = source / split / "annotations"
    if not image_dir.is_dir():
        return Counter()
    label_dir = output / "labels" / split
    out_image_dir = output / "images" / split
    label_dir.mkdir(parents=True, exist_ok=True)
    out_image_dir.mkdir(parents=True, exist_ok=True)

    histogram: Counter = Counter()
    from PIL import Image

    for annotation_path in sorted(annotation_dir.glob("*.json")):
        stem = annotation_path.stem
        image_path = image_dir / f"{stem}.png"
        if not image_path.is_file():
            continue
        with Image.open(image_path) as image:
            width, height = image.size
        payload = json.loads(annotation_path.read_text())
        lines: list[str] = []
        seen: set[str] = set()
        for item in payload.get("form") or []:
            category = item.get("category")
            index = CLASS_INDEX.get(category)
            box = item.get("box") or []
            if index is None or len(box) != 4:
                continue
            x, y, box_width, box_height = (float(value) for value in box)
            if box_width <= 1 or box_height <= 1:
                continue
            # clip to the page before normalising
            x1 = max(0.0, min(x, width))
            y1 = max(0.0, min(y, height))
            x2 = max(0.0, min(x + box_width, width))
            y2 = max(0.0, min(y + box_height, height))
            if x2 - x1 <= 1 or y2 - y1 <= 1:
                continue
            centre_x = (x1 + x2) / 2 / width
            centre_y = (y1 + y2) / 2 / height
            norm_width = (x2 - x1) / width
            norm_height = (y2 - y1) / height
            line = f"{index} {centre_x:.6f} {centre_y:.6f} {norm_width:.6f} {norm_height:.6f}"
            if line in seen:
                # the source repeats the same box for every text line inside it
                continue
            seen.add(line)
            lines.append(line)
            histogram[category] += 1
        (label_dir / f"{stem}.txt").write_text("\n".join(lines) + ("\n" if lines else ""))
        shutil.copyfile(image_path, out_image_dir / image_path.name)
    return histogram


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, help="dataset root with <split>/images and <split>/annotations")
    parser.add_argument("--output", required=True, help="destination for the YOLO dataset")
    args = parser.parse_args()

    source = Path(args.source)
    output = Path(args.output)
    if not source.is_dir():
        raise SystemExit(f"source directory not found: {source}")

    totals: Counter = Counter()
    for split in SPLITS:
        histogram = convert_split(source, output, split)
        if histogram:
            print(f"{split}: {sum(histogram.values())} boxes across {len(histogram)} classes")
            totals.update(histogram)

    data_yaml = output / "data.yaml"
    data_yaml.write_text(
        "\n".join(
            [
                "# generated by tools/prepare_layout_dataset.py",
                f"path: {output.resolve()}",
                "train: images/train",
                "val: images/val",
                "test: images/test",
                f"nc: {len(CLASSES)}",
                "names:",
                *[f"  {index}: {name}" for index, name in enumerate(CLASSES)],
                "",
            ]
        )
    )
    print(f"\nwrote {data_yaml}")
    for name in CLASSES:
        print(f"  {name:16s} {totals.get(name, 0)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())